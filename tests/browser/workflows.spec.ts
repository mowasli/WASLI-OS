 await expect(dialog).toHaveCount(0);
 await first.getByRole('button',{name:'Create research project',exact:true}).click();
 await expect(dialog.getByLabel('Project name')).toHaveValue(/^Research:/);
 await expect(dialog.getByLabel('Objective')).toHaveValue(/does not represent an application/);
 await dialog.getByRole('button',{name:'Close dialog',exact:true}).click();
 await page.getByRole('button',{name:/^Intelligence/}).click();
