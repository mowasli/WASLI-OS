-- Authorized local reference material and private, workspace-scoped assistant history.
-- Apply to managed PostgreSQL only after explicit production-migration approval.
CREATE TABLE IF NOT EXISTS knowledge_documents (
 id uuid PRIMARY KEY, workspace_id text NOT NULL REFERENCES workspaces(id),
 title text NOT NULL, source_url text NOT NULL, source_type text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(id,workspace_id)
);
CREATE TABLE IF NOT EXISTS knowledge_chunks (
 id uuid PRIMARY KEY, document_id uuid NOT NULL, workspace_id text NOT NULL REFERENCES workspaces(id),
 section text NOT NULL, content text NOT NULL,
 verified_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(document_id,workspace_id) REFERENCES knowledge_documents(id,workspace_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS assistant_messages (
 id uuid PRIMARY KEY, workspace_id text NOT NULL REFERENCES workspaces(id),
 user_id uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 role text NOT NULL CHECK(role IN ('user','assistant')), content text NOT NULL,
 mode text NOT NULL DEFAULT 'rules-based' CHECK(mode='rules-based'),
 sources jsonb NOT NULL DEFAULT '[]', created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE assistant_messages ADD COLUMN IF NOT EXISTS sequence bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX IF NOT EXISTS knowledge_chunks_workspace_idx ON knowledge_chunks(workspace_id,document_id);
CREATE INDEX IF NOT EXISTS assistant_messages_scope_idx ON assistant_messages(workspace_id,user_id,created_at);
ALTER TABLE knowledge_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE knowledge_chunks ENABLE ROW LEVEL SECURITY;
ALTER TABLE assistant_messages ENABLE ROW LEVEL SECURITY;
-- No browser write policies are granted. Server endpoints enforce membership.
-- Authenticated Supabase reads additionally require membership in the row scope.
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname='auth') THEN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='knowledge_documents' AND policyname='knowledge_document_member_read') THEN
   EXECUTE 'CREATE POLICY knowledge_document_member_read ON knowledge_documents FOR SELECT USING (EXISTS (SELECT 1 FROM workspace_memberships m WHERE m.workspace_id=knowledge_documents.workspace_id AND m.user_id=auth.uid()))';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='knowledge_chunks' AND policyname='knowledge_chunk_member_read') THEN
   EXECUTE 'CREATE POLICY knowledge_chunk_member_read ON knowledge_chunks FOR SELECT USING (EXISTS (SELECT 1 FROM workspace_memberships m WHERE m.workspace_id=knowledge_chunks.workspace_id AND m.user_id=auth.uid()))';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='assistant_messages' AND policyname='assistant_own_member_read') THEN
   EXECUTE 'CREATE POLICY assistant_own_member_read ON assistant_messages FOR SELECT USING (user_id=auth.uid() AND EXISTS (SELECT 1 FROM workspace_memberships m WHERE m.workspace_id=assistant_messages.workspace_id AND m.user_id=auth.uid()))';
  END IF;
 END IF;
END $$;
